import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'
test('public pages, login cookies, admin and mobile layouts', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await fs.mkdir('../docs/screenshots', { recursive: true })
  const ready = async () => {
    await page.evaluate(() => document.fonts.ready)
    await page.waitForTimeout(900)
  }
  const reveal = async () => {
    for (const el of await page.locator('main [data-reveal]').all()) {
      await el.scrollIntoViewIfNeeded()
      await page.waitForTimeout(150)
    }
    await page.evaluate(() => scrollTo(0, 0))
    await page.waitForTimeout(500)
  }
  await page.goto('/')
  await expect(
    page.getByRole('heading', { name: 'Mở một trang sách. Mở cả thế giới.' }),
  ).toBeVisible()
  await expect(page.locator('.hero-book')).toHaveCount(3)
  await reveal()
  await ready()
  await ready()
  await page.screenshot({ path: '../docs/screenshots/home-desktop.png', fullPage: true })
  await page.goto('/catalog')
  await expect(page.locator('.book-card')).toHaveCount(12)
  await ready()
  await page.screenshot({ path: '../docs/screenshots/catalog-desktop.png', fullPage: true })
  await page.getByRole('textbox', { name: 'Tìm theo tên sách, tác giả, ISBN…' }).fill('Atomic')
  await expect(page.locator('.book-card')).toHaveCount(1)
  await page.locator('.book-title').click()
  await expect(page.locator('.detail-copy h1')).toContainText('Atomic')
  await ready()
  await page.screenshot({ path: '../docs/screenshots/detail-desktop.png', fullPage: true })
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'Địa chỉ email' }).fill('admin@librivo.local')
  await page.getByLabel('Mật khẩu', { exact: true }).fill('AdminDemo!2026')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).toHaveURL('/admin')
  await expect(page.locator('.kpi-card')).toHaveCount(8)
  await expect(page.getByText('Chưa thể tải dữ liệu')).toHaveCount(0)
  await ready()
  await page.screenshot({ path: '../docs/screenshots/dashboard-desktop.png', fullPage: true })
  await page.goto('/admin/books')
  await expect(page.locator('tbody tr')).toHaveCount(12)
  await page.getByRole('button', { name: 'Thêm sách mới' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Đóng', exact: true }).click()
  await page.getByRole('button', { name: 'Chế độ tối' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await ready()
  await page.screenshot({ path: '../docs/screenshots/admin-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Chế độ sáng' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/admin')
  await expect(page.locator('.kpi-card')).toHaveCount(8)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await ready()
  await page.screenshot({ path: '../docs/screenshots/dashboard-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Mở menu', exact: true }).click()
  await expect(page.locator('.sidebar.mobile-open')).toBeVisible()
  await page.locator('.sidebar-close-mobile').click()
  await page.goto('/')
  await expect(page.locator('.hero-book')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await reveal()
  await ready()
  await page.screenshot({ path: '../docs/screenshots/home-mobile.png', fullPage: true })
  await page.goto('/catalog')
  await expect(page.locator('.book-card')).toHaveCount(12)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await ready()
  await page.screenshot({ path: '../docs/screenshots/catalog-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
