<?php

use App\Http\Controllers\Api\AdminController;
use App\Http\Controllers\Api\AuthController;
use App\Http\Controllers\Api\BookController;
use App\Http\Controllers\Api\CirculationController;
use App\Http\Controllers\Api\CommunityController;
use App\Http\Controllers\Api\ReportController;
use App\Http\Controllers\Api\TaxonomyController;
use Illuminate\Support\Facades\Route;

Route::post('auth/login', [AuthController::class, 'login'])->middleware('throttle:6,1');
Route::post('auth/register', [AuthController::class, 'register'])->middleware('throttle:5,1');
Route::post('auth/forgot-password', [AuthController::class, 'forgot'])->middleware('throttle:3,1');
Route::post('auth/reset-password', [AuthController::class, 'reset'])->middleware('throttle:6,1');
Route::get('books', [BookController::class, 'index']);
Route::get('books/{book}', [BookController::class, 'show'])->whereNumber('book');
Route::get('public/stats', [AdminController::class, 'publicStats']);
Route::get('public/settings', [AdminController::class, 'publicSettings']);
Route::get('taxonomy/{type}', [TaxonomyController::class, 'index'])->whereIn('type', ['categories', 'authors', 'publishers', 'shelves']);

Route::middleware(['auth:sanctum', 'active'])->group(function (): void {
    Route::get('me', [AuthController::class, 'me']);
    Route::post('auth/logout', [AuthController::class, 'logout']);
    Route::post('me/profile', [AuthController::class, 'profile']);
    Route::put('me/password', [AuthController::class, 'password']);
    Route::get('me/summary', [CommunityController::class, 'summary']);
    Route::get('favorites', [CommunityController::class, 'favorites']);
    Route::put('favorites/{book}', [CommunityController::class, 'favorite']);
    Route::get('reviews', [CommunityController::class, 'reviews']);
    Route::put('books/{book}/review', [CommunityController::class, 'review']);
    Route::delete('reviews/{review}', [CommunityController::class, 'deleteReview']);
    Route::get('notifications', [CommunityController::class, 'notifications']);
    Route::put('notifications/{id}/read', [CommunityController::class, 'readNotification']);
    Route::get('loans', [CirculationController::class, 'loans']);
    Route::post('loan-requests', [CirculationController::class, 'request'])->middleware('throttle:30,1');
    Route::post('loans/{loan}/{action}', [CirculationController::class, 'action'])->whereIn('action', ['approve', 'handoff', 'reject', 'return', 'cancel', 'renew']);
    Route::get('reservations', [CirculationController::class, 'reservations']);
    Route::post('reservations', [CirculationController::class, 'reserve']);
    Route::delete('reservations/{reservation}', [CirculationController::class, 'cancelReservation']);
    Route::get('fines', [CirculationController::class, 'fines']);
    Route::post('fines/{fine}/payments', [CirculationController::class, 'pay'])->middleware('permission:fines.collect');
    Route::get('loan-renewals', [CirculationController::class, 'renewals'])->middleware('permission:loans.approve');
    Route::put('loan-renewals/{renewal}', [CirculationController::class, 'renewalDecision'])->middleware('permission:loans.approve');
    Route::post('books', [BookController::class, 'store'])->middleware('permission:books.create');
    Route::put('books/{book}', [BookController::class, 'update'])->middleware('permission:books.update');
    Route::delete('books/{book}', [BookController::class, 'destroy'])->middleware('permission:books.delete');
    Route::post('uploads/cover', [BookController::class, 'upload'])->middleware('permission:books.update');
    Route::get('metadata/isbn', [BookController::class, 'metadata'])->middleware(['permission:books.create', 'throttle:20,1']);
    Route::get('book-copies', [BookController::class, 'copies'])->middleware('permission:books.update');
    Route::get('book-copies/{copy}', [BookController::class, 'copyHistory'])->middleware('permission:books.update');
    Route::post('books/{book}/copies', [BookController::class, 'addCopies'])->middleware('permission:books.create');
    Route::put('book-copies/{copy}', [BookController::class, 'updateCopy'])->middleware('permission:books.update');
    Route::post('taxonomy/{type}', [TaxonomyController::class, 'store'])->middleware('permission:taxonomy.manage');
    Route::put('taxonomy/{type}/{id}', [TaxonomyController::class, 'update'])->middleware('permission:taxonomy.manage');
    Route::delete('taxonomy/{type}/{id}', [TaxonomyController::class, 'destroy'])->middleware('permission:taxonomy.manage');
    Route::get('dashboard', [AdminController::class, 'dashboard'])->middleware('permission:dashboard.view');
    Route::get('members', [AdminController::class, 'members'])->middleware('permission:members.manage');
    Route::post('members', [AdminController::class, 'createMember'])->middleware('permission:members.manage');
    Route::get('members/{user}', [AdminController::class, 'member'])->middleware('permission:members.manage');
    Route::put('members/{user}', [AdminController::class, 'updateMember'])->middleware('permission:members.manage');
    Route::get('roles', [AdminController::class, 'roles'])->middleware('permission:roles.manage');
    Route::post('roles', [AdminController::class, 'storeRole'])->middleware('permission:roles.manage');
    Route::put('roles/{role}', [AdminController::class, 'updateRole'])->middleware('permission:roles.manage');
    Route::get('settings', [AdminController::class, 'settings'])->middleware('permission:settings.manage');
    Route::put('settings', [AdminController::class, 'updateSettings'])->middleware('permission:settings.manage');
    Route::get('audit-logs', [AdminController::class, 'auditLogs'])->middleware('permission:audit.view');
    Route::get('reports', [ReportController::class, 'index'])->middleware('permission:reports.view');
    Route::get('reports/export', [ReportController::class, 'export'])->middleware('permission:reports.export');
    Route::post('books/import',[ReportController::class, 'import'])->middleware('permission:books.create');
    Route::get('backup',[ReportController::class, 'backup'])->middleware('permission:settings.manage');
});
